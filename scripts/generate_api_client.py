from __future__ import annotations

import argparse
import json
import tempfile
from pathlib import Path
from typing import Any, cast

from fieldledger.main import app

ROOT = Path(__file__).resolve().parents[1]
SNAPSHOT = ROOT / "apps" / "api" / "openapi.json"
GENERATED = ROOT / "packages" / "api-client" / "src" / "generated.ts"


def ts_type(schema: dict[str, Any] | None) -> str:
    if not schema:
        return "unknown"
    if "$ref" in schema:
        return f'components["schemas"]["{str(schema["$ref"]).rsplit("/", 1)[-1]}"]'
    if "anyOf" in schema:
        return " | ".join(ts_type(item) for item in schema["anyOf"])
    if "oneOf" in schema:
        return " | ".join(ts_type(item) for item in schema["oneOf"])
    if "enum" in schema:
        return " | ".join(json.dumps(item) for item in schema["enum"])
    schema_type = schema.get("type")
    if schema_type == "array":
        return f"Array<{ts_type(schema.get('items'))}>"
    if schema_type == "object" or "properties" in schema:
        properties = cast(dict[str, dict[str, Any]], schema.get("properties", {}))
        required = set(schema.get("required", []))
        fields = [
            f"{json.dumps(name)}{'?' if name not in required else ''}: {ts_type(value)};"
            for name, value in sorted(properties.items())
        ]
        if fields:
            return "{ " + " ".join(fields) + " }"
        additional = schema.get("additionalProperties")
        return (
            f"Record<string, {ts_type(additional)}>"
            if isinstance(additional, dict)
            else "Record<string, unknown>"
        )
    return {
        "string": "string",
        "integer": "number",
        "number": "number",
        "boolean": "boolean",
        "null": "null",
    }.get(str(schema_type), "unknown")


def response_type(operation: dict[str, Any]) -> str:
    responses = cast(dict[str, dict[str, Any]], operation.get("responses", {}))
    selected = next(
        (value for code, value in sorted(responses.items()) if code.startswith("2")),
        None,
    )
    if selected is None:
        return "unknown"
    content = cast(dict[str, dict[str, Any]], selected.get("content", {}))
    media = content.get("application/json") or next(iter(content.values()), {})
    return ts_type(cast(dict[str, Any], media.get("schema", {})))


def request_type(operation: dict[str, Any]) -> str:
    body = cast(dict[str, Any], operation.get("requestBody", {}))
    if not body:
        return "Record<string, never>"
    content = cast(dict[str, dict[str, Any]], body.get("content", {}))
    media = content.get("application/json") or next(iter(content.values()), {})
    return ts_type(cast(dict[str, Any], media.get("schema", {})))


def parameter_type(operation: dict[str, Any], location: str) -> str:
    parameters = cast(list[dict[str, Any]], operation.get("parameters", []))
    selected = [item for item in parameters if item.get("in") == location]
    if not selected:
        return "Record<string, never>"
    fields = []
    for item in sorted(selected, key=lambda value: str(value["name"])):
        optional = "" if item.get("required") else "?"
        fields.append(
            f'{json.dumps(str(item["name"]))}{optional}: '
            f'{ts_type(cast(dict[str, Any], item.get("schema", {})))};'
        )
    return "{ " + " ".join(fields) + " }"


def generate_typescript(schema: dict[str, Any]) -> str:
    schemas = cast(
        dict[str, dict[str, Any]],
        cast(dict[str, Any], schema.get("components", {})).get("schemas", {}),
    )
    paths = cast(dict[str, dict[str, dict[str, Any]]], schema["paths"])
    operations: list[tuple[str, str, str, dict[str, Any]]] = []
    for path, methods in sorted(paths.items()):
        for method, operation in sorted(methods.items()):
            if method not in {"get", "post", "put", "patch", "delete"}:
                continue
            operation_id = str(operation["operationId"])
            operations.append((operation_id, method.upper(), path, operation))

    lines = [
        "// Generated by scripts/generate_api_client.py. Do not edit.",
        "",
        "export interface components {",
        "  schemas: {",
    ]
    for name, definition in sorted(schemas.items()):
        lines.append(f"    {json.dumps(name)}: {ts_type(definition)};")
    lines.extend(["  };", "}", "", "export interface operations {"])
    for operation_id, _method, _path, operation in operations:
        lines.extend(
            [
                f"  {json.dumps(operation_id)}: {{",
                f"    path: {parameter_type(operation, 'path')};",
                f"    query: {parameter_type(operation, 'query')};",
                f"    headers: {parameter_type(operation, 'header')};",
                f"    requestBody: {request_type(operation)};",
                f"    response: {response_type(operation)};",
                "  };",
            ]
        )
    lines.extend(["}", "", "export interface paths {"])
    for path, methods in sorted(paths.items()):
        lines.append(f"  {json.dumps(path)}: {{")
        for method, operation in sorted(methods.items()):
            if method in {"get", "post", "put", "patch", "delete"}:
                lines.append(
                    f"    {method}: operations[{json.dumps(str(operation['operationId']))}];"
                )
        lines.append("  };")
    lines.extend(["}", "", "export const operationRegistry = {"])
    for operation_id, method, path, _operation in operations:
        lines.append(
            f"  {json.dumps(operation_id)}: {{ method: {json.dumps(method)}, "
            f"path: {json.dumps(path)} }},"
        )
    lines.extend(
        [
            "} as const;",
            "",
            "export type OperationId = keyof operations;",
            "export interface FieldLedgerProblem extends Record<string, unknown> {",
            "  type?: string;",
            "  title?: string;",
            "  status?: number;",
            "  detail?: string;",
            "  instance?: string;",
            "  correlation_id?: string;",
            "}",
            "",
            "export class FieldLedgerApiError extends Error {",
            "  public readonly name = \"FieldLedgerApiError\";",
            "",
            "  public constructor(",
            "    public readonly status: number,",
            "    public readonly problem: FieldLedgerProblem | undefined,",
            "  ) {",
            "    super(",
            "      problem?.detail ?? problem?.title",
            "        ?? `FieldLedger API request failed (${status})`,",
            "    );",
            "  }",
            "}",
            "",
            "export type OperationArguments<Id extends OperationId> = {",
            "  path: operations[Id][\"path\"];",
            "  query?: operations[Id][\"query\"];",
            "  headers?: operations[Id][\"headers\"];",
            "} & (operations[Id][\"requestBody\"] extends Record<string, never>",
            "  ? { body?: never }",
            "  : { body: operations[Id][\"requestBody\"] });",
            "",
            "export class FieldLedgerClient {",
            "  public constructor(",
            "    private readonly baseUrl: string,",
            "    private readonly token: string,",
            "    private readonly fetcher: typeof fetch = fetch,",
            "  ) {}",
            "",
            "  public async request<Id extends OperationId>(",
            "    operationId: Id,",
            "    args: OperationArguments<Id>,",
            "  ): Promise<operations[Id][\"response\"]> {",
            "    const operation = operationRegistry[operationId];",
            "    let path: string = operation.path;",
            "    for (const [key, value] of Object.entries(args.path)) {",
            "      path = path.replace(`{${key}}`, encodeURIComponent(String(value)));",
            "    }",
            "    const url = new URL(path, this.baseUrl);",
            "    for (const [key, value] of Object.entries(args.query ?? {})) {",
            "      if (value !== undefined) url.searchParams.set(key, String(value));",
            "    }",
            "    const init: RequestInit = {",
            "      method: operation.method,",
            "      headers: {",
            "        \"content-type\": \"application/json\",",
            "        ...(this.token.length === 0",
            "          ? {}",
            "          : { authorization: `Bearer ${this.token}` }),",
            "        ...args.headers,",
            "      },",
            "    };",
            "    if (args.body !== undefined) init.body = JSON.stringify(args.body);",
            "    const response = await this.fetcher(url, init);",
            "    const text = await response.text();",
            "    let payload: unknown;",
            "    try {",
            "      payload = text.length === 0 ? undefined : JSON.parse(text);",
            "    } catch {",
            "      payload = undefined;",
            "    }",
            "    if (!response.ok) {",
            "      const problem = payload !== null",
            "        && typeof payload === \"object\"",
            "        && !Array.isArray(payload)",
            "        ? payload as FieldLedgerProblem",
            "        : undefined;",
            "      throw new FieldLedgerApiError(response.status, problem);",
            "    }",
            "    return payload as operations[Id][\"response\"];",
            "  }",
            "}",
            "",
        ]
    )
    return "\n".join(lines)


def generated_content() -> tuple[str, str]:
    schema = app.openapi()
    snapshot = json.dumps(schema, ensure_ascii=True, indent=2, sort_keys=True) + "\n"
    return snapshot, generate_typescript(schema)


def check() -> int:
    snapshot, generated = generated_content()
    with tempfile.TemporaryDirectory(prefix="fieldledger-api-client-") as directory:
        temporary = Path(directory)
        snapshot_path = temporary / "openapi.json"
        generated_path = temporary / "generated.ts"
        snapshot_path.write_text(snapshot, encoding="utf-8")
        generated_path.write_text(generated, encoding="utf-8")
        drift = []
        if not SNAPSHOT.exists() or SNAPSHOT.read_bytes() != snapshot_path.read_bytes():
            drift.append(str(SNAPSHOT.relative_to(ROOT)))
        if not GENERATED.exists() or GENERATED.read_bytes() != generated_path.read_bytes():
            drift.append(str(GENERATED.relative_to(ROOT)))
    if drift:
        print("OpenAPI/client drift: " + ", ".join(drift))
        return 1
    print("OpenAPI snapshot and generated client are current.")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if args.check:
        return check()
    snapshot, generated = generated_content()
    SNAPSHOT.parent.mkdir(parents=True, exist_ok=True)
    GENERATED.parent.mkdir(parents=True, exist_ok=True)
    SNAPSHOT.write_text(snapshot, encoding="utf-8")
    GENERATED.write_text(generated, encoding="utf-8")
    print(f"Generated {SNAPSHOT.relative_to(ROOT)} and {GENERATED.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
